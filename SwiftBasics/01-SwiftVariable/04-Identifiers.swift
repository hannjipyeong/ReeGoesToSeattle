// simple aja aturan sebenernya
// harus dimulai dengan huruf atau underscore
// bisa diikuti dengan angka setelah huruf pertama
// hindari penggunaan kata kunci kecuali dilindungi dengan backticks

// ini kalau dimulai dengan huruf atau underscore
let nama = "Raihan"
let _nama = "Zhaky"
print(nama)
print(_nama)

// ini kalau dimulai dengan angka setelah huruf pertama
let nama1 = "Raihan"
print(nama1)

// ini kalau dimulai dengan unicode
let 🐶 = "ini adalah anjing"
print(🐶)

// ini kalau menggunakan keyword, penulisan harus dilindungi dengan backticks
let `func` = "ini adalah fungsi"
print(`func`)

